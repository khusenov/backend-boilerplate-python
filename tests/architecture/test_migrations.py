def test_deploys_skip_a_database_ahead_of_the_code(empty_database_url: str) -> None:
    engine = create_engine(empty_database_url, poolclass=NullPool)
    with alembic_config(empty_database_url) as config:
        config.cmd_opts = Namespace(x=["ahead=skip"])
        command.upgrade(config, "head")
        with engine.begin() as connection:
            connection.execute(text("UPDATE alembic_version SET version_num = 'ffff'"))
        with redirect_stdout(io.StringIO()) as output:
            command.upgrade(config, "head")
            command.check(config)
        config.cmd_opts = None
        with pytest.raises(
            CommandError, match="Can't locate revision identified by 'ffff'"
        ):
            command.upgrade(config, "head")

    assert current_heads(empty_database_url) == ("ffff",)
    assert "migrations.skipped" in output.getvalue()


def test_migrations_wait_for_the_migration_lock(empty_database_url: str) -> None:
    impatient_url = (
        make_url(empty_database_url)
        .update_query_dict({"options": "-c statement_timeout=500"})
        .render_as_string(hide_password=False)
    )
    engine = create_engine(empty_database_url, poolclass=NullPool)
    with engine.connect() as holder:
        holder.execute(text("SELECT pg_advisory_lock(:id)"), {"id": MIGRATION_LOCK_ID})
        with (
            alembic_config(impatient_url) as config,
            pytest.raises(OperationalError, match="pg_advisory_lock") as caught,
        ):
            command.upgrade(config, "head")

    assert "SQL parameters hidden" in str(caught.value)


def test_migrations_time_out_connecting(empty_database_url: str) -> None:
    timeouts: set[str | None] = set()

    def observe(conn: Connection, **_: object) -> None:
        driver = conn.connection.driver_connection
        assert driver is not None
        timeouts.add(driver.info.get_parameters().get("connect_timeout"))

    event.listen(Engine, "before_cursor_execute", observe, named=True)
    try:
        with alembic_config(empty_database_url) as config:
            command.upgrade(config, "head")
    finally:
        event.remove(Engine, "before_cursor_execute", observe)

    assert timeouts == {"5"}


def test_migrations_run_holding_the_lock_with_a_lock_timeout(
    empty_database_url: str,
) -> None:
    observer = create_engine(empty_database_url, poolclass=NullPool)
    seen: set[tuple[bool, str]] = set()

    def observe(conn: Connection, statement: str, **_: object) -> None:
        if statement.startswith("INSERT INTO alembic_version"):
            with observer.connect() as other:
                free = other.scalar(
                    text("SELECT pg_try_advisory_lock_shared(:id)"),
                    {"id": MIGRATION_LOCK_ID},
                )
            seen.add((free, conn.scalar(text("SHOW lock_timeout"))))

    event.listen(Engine, "before_cursor_execute", observe, named=True)
    try:
        with alembic_config(empty_database_url) as config:
            command.upgrade(config, "head")
    finally:
        event.remove(Engine, "before_cursor_execute", observe)

    assert seen == {(False, "5s")}


def test_each_revision_commits_on_its_own(empty_database_url: str) -> None:
    commits: list[Connection] = []

    def record(connection: Connection) -> None:
        commits.append(connection)

    event.listen(Engine, "commit", record)
    try:
        with alembic_config(empty_database_url) as config:
            command.upgrade(config, "head")
    finally:
        event.remove(Engine, "commit", record)

    assert len(commits) == len(revision_modules()) + 1


def test_every_newer_procrastinate_migration_has_a_revision() -> None:
    modules = revision_modules()
    [vendored] = [
        module.procrastinate_version
        for module in modules
        if hasattr(module, "procrastinate_version")
    ]
    covered = {getattr(module, "procrastinate_migration", None) for module in modules}
    installed = version_of(metadata.version("procrastinate"))
    migrations = [
        path.name
        for path in resources.files("procrastinate.sql.migrations").iterdir()
        if path.name.endswith(".sql")
    ]
    due = {
        name
        for name in migrations
        if version_of(name) > version_of(vendored)
        and not (version_of(name) == installed and "_post_" in name)
    }

    assert migrations
    assert due - covered == set()


def test_env_reads_metadata_through_bootstrap() -> None:
    scripts = ScriptDirectory.from_config(Config(toml_file=PYPROJECT))
    env = ast.parse(Path(scripts.env_py_location).read_text())
    imported = {
        (node.module, alias.asname or alias.name)
        for node in ast.walk(env)
        if isinstance(node, ast.ImportFrom)
        for alias in node.names
    }
    targets = [
        ast.unparse(node.value)
        for node in ast.walk(env)
        if isinstance(node, ast.keyword) and node.arg == "target_metadata"
    ]

    assert ("app.bootstrap", "metadata") in imported
    assert targets == ["metadata"]


